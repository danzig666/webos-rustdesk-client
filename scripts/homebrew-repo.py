#!/usr/bin/env python3
"""Build the project's webOS Homebrew Channel catalog from a release manifest.

Writes <out>/apps.json (repository index in the repo.webosbrew.org format the Homebrew Channel
reads: {"packages": [{id, title, iconUri, shortDescription, manifestUrl, manifest}]}), the
manifest itself and the icon. The release workflow publishes the directory as the
`homebrew-repo` branch, served from raw.githubusercontent.com (which allows the cross-origin
requests the Homebrew Channel makes)."""
import argparse
import json
import shutil
from pathlib import Path

SHORT = (
    "Control your computer from the TV with the regular RustDesk app: Magic Remote mouse, "
    "full on-screen keyboard (US/Hungarian), hardware video, audio. Community project, "
    "not affiliated with RustDesk or LG."
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--icon", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    manifest = json.loads(Path(a.manifest).read_text())
    for key in ("id", "version", "title", "ipkUrl", "ipkHash", "iconUri"):
        if key not in manifest:
            raise SystemExit(f"manifest lacks {key}")
    name = f"{manifest['id']}.manifest.json"
    (out / name).write_text(json.dumps(manifest, indent=2) + "\n")
    shutil.copyfile(a.icon, out / "icon.png")
    index = {
        "paging": {"page": 1, "count": 1, "maxPage": 1, "itemsTotal": 1},
        "packages": [
            {
                "id": manifest["id"],
                "title": manifest["title"],
                "iconUri": manifest["iconUri"],
                "shortDescription": SHORT,
                "manifestUrl": name,
                "manifest": manifest,
            }
        ],
    }
    (out / "apps.json").write_text(json.dumps(index, indent=2) + "\n")
    (out / "README.md").write_text(
        "# RemoteDesk TV Homebrew Channel catalog\n\n"
        "Generated by the release workflow; do not edit. Add this URL in the Homebrew Channel "
        "(Settings → Add repository):\n\n"
        "    https://raw.githubusercontent.com/danzig666/webos-rustdesk-client/homebrew-repo/apps.json\n"
    )
    print(json.dumps(index, indent=2))


if __name__ == "__main__":
    main()
